def check():
    import re
    seen = {}
    for c, cs in CITIES.items():
        assert c in COUNTRIES, c
        for x in cs:
            assert x not in seen, (x, c, seen.get(x))
            seen[x] = c
            for k in COUNTRIES:  # no country name as a whole word inside a city name
                assert not re.search(r"\b%s\b" % re.escape(k.lower()), x.lower()), (x, k)
            assert x != COUNTRIES[c][2], x
    caps = [v[2] for v in COUNTRIES.values()]
    assert len(set(caps)) == len(caps)
    return len(seen)


